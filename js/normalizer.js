export function normalizeCityTown(rawCity, rawAddress = '') {
  let raw = (rawCity || '').trim();
  if (!raw || raw.toLowerCase() === 'null') return 'Other';

  const low = raw.toLowerCase();
  if (aucklandSuburbs.has(low)) return 'Auckland';
  if (chchSuburbs.has(low)) return 'Christchurch';
  if (wellingtonSuburbs.has(low)) return 'Wellington';
  if (taurangaSuburbs.has(low)) return 'Tauranga';
  if (dunedinSuburbs.has(low)) return 'Dunedin';

  if (low.includes('auckland') || low.includes('north shore') || low.includes('manukau') || low.includes('waitakere')) {
    return 'Auckland';
  } else if (low.includes('christchurch')) {
    return 'Christchurch';
  } else if (low.includes('wellington') || low.includes('porirua') || low.includes('lower hutt') || low.includes('upper hutt')) {
    return 'Wellington';
  } else if (low.includes('tauranga')) {
    return 'Tauranga';
  } else if (low.includes('hamilton')) {
    return 'Hamilton';
  } else if (low.includes('dunedin')) {
    return 'Dunedin';
  } else if (low.includes('queenstown') || low.includes('arrowtown')) {
    return 'Queenstown';
  } else if (low.includes('wanaka') || low.includes('wānaka')) {
    return 'Wānaka';
  }
  return raw.charAt(0).toUpperCase() + raw.slice(1);
}
